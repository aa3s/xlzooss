export function formatDH(amount: number): string {
  return `${Math.round(amount).toLocaleString('en-US')} DH`;
}

export function formatCompactDH(amount: number): string {
  if (amount >= 1_000_000) {
    const millions = amount / 1_000_000;
    return `${millions % 1 === 0 ? millions.toFixed(0) : millions.toFixed(2)}M DH`;
  }
  if (amount >= 1_000) {
    return `${(amount / 1_000).toFixed(1)}K DH`;
  }
  return `${Math.round(amount)} DH`;
}
